public class DataTypes {
    public static void main(String[] args) {
        // Primitive Data Types
        byte byteValue = 10; // Byte
        int intValue = 25; // Integer
        short shortValue = 100; // Short
        long longValue = 100000L; // Long
        float floatValue = 10.5f; // Float
        double doubleValue = 50000.50; // Double
        char charValue = 'A'; // Character
        boolean booleanValue = true; // Boolean

        // Non-Primitive Data Types
        String stringValue = "John Doe"; // String

        // Displaying the values
        System.out.println("Name: " + stringValue);
        System.out.println("Age: " + intValue);
        System.out.println("Salary: " + doubleValue);
        System.out.println("Grade: " + charValue);
        System.out.println("Is Employed: " + booleanValue);
        System.out.println("Byte Value: " + byteValue);
        System.out.println("Short Value: " + shortValue);
        System.out.println("Long Value: " + longValue);
        System.out.println("Float Value: " + floatValue);

    }
    
}
